//! Native spreadsheet parsing, with no LibreOffice.
//!
//! A spreadsheet is not a document with pages: it is a grid that is read by scrolling,
//! and its real size is often far larger than the screen. Three consequences shape this
//! module:
//!
//! - Only a window of rows is ever returned. A sheet can hold a million rows and the
//!   renderer draws a few hundred of them; serialising the whole grid across IPC would
//!   cost hundreds of megabytes to show one screenful.
//! - The display text is derived here, not in the renderer, because the value kinds are
//!   calamine's own and formatting a float or a date needs the Rust side's types.
//! - Cell values come from calamine, but the parts calamine's unified reader does not
//!   expose - merged regions and column widths - are read from the OOXML parts through
//!   zip_vfs, the reader this crate already uses for decks. That keeps the calamine
//!   surface small and explicit; every call is listed in the report.
//!
//! Three file shapes are read:
//!
//! - .xlsx / .xlsm / .xlsb / .ods: calamine's OOXML and ODF readers
//! - .xls: calamine's BIFF8 reader
//! - .csv / .tsv: by hand. A CSV has no container at all, so there is nothing for
//!   calamine to open, and a GBK fallback is needed because Chinese teaching material
//!   is frequently saved in the system code page rather than in UTF-8.

use std::path::Path;

use calamine::{open_workbook_auto, Data, Range, Reader, Sheets};

/// Rows returned by one call when the caller does not ask for a window.
///
/// Sized to a tall projector screen: a 1080p window at the default row height shows
/// about 45 rows, and a window of 500 leaves the renderer room to scroll ahead without
/// asking again on every wheel tick.
pub const DEFAULT_ROW_WINDOW: u32 = 500;

/// Largest window a single call will return.
///
/// The limit exists so a caller cannot ask for the whole sheet by accident: 5000 rows
/// of a wide sheet is already several megabytes of JSON.
pub const MAX_ROW_WINDOW: u32 = 5000;

/// Largest number of columns returned for one sheet.
///
/// A mis-authored workbook can claim 16384 columns; a teaching sheet uses a handful.
/// Clamping keeps a single row from becoming a megabyte of empty cells.
pub const MAX_COLUMNS: u32 = 256;

/// Upper bound on a delimited file, matching the source size limit elsewhere.
const MAX_TEXT_BYTES: u64 = 200 * 1024 * 1024;

/// The two-byte GBK decoding table, generated by scripts/gen-gbk-table.mjs.
///
/// GBK orders its ideographs by pinyin rather than by code point, so the mapping is not
/// derivable and has to be carried. 126 lead bytes by 190 trail bytes, one little-endian
/// u16 each, zero meaning "not mapped".
const GBK_TABLE: &[u8] = include_bytes!("gbk_table.bin");
/// Lead byte count and trail byte count of the table above.
const GBK_LEADS: usize = 126;
const GBK_TRAILS: usize = 190;

/// A cell as the renderer draws it.
#[derive(Debug, Clone, PartialEq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SheetCell {
    /// Zero-based column index within the sheet, not within the returned window.
    pub col: u32,
    /// What the user should see: formatted number, date, boolean, or text.
    pub text: String,
    /// Which kind of value produced the text, so the view can align and style it.
    pub kind: CellKind,
}

/// What a cell holds.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "lowercase")]
pub enum CellKind {
    /// A number.
    Number,
    /// A date or time.
    Date,
    /// Text, including the string form of an error value.
    Text,
    /// A boolean.
    Bool,
}

/// One row of a sheet, sparse: only the cells that hold something.
#[derive(Debug, Clone, PartialEq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SheetRow {
    /// Zero-based row index within the sheet.
    pub row: u32,
    pub cells: Vec<SheetCell>,
}

/// A rectangular block of merged cells, in zero-based grid coordinates.
///
/// Both ends are inclusive, which is how the renderer needs them to draw a span.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct MergedRegion {
    pub first_row: u32,
    pub first_col: u32,
    pub last_row: u32,
    pub last_col: u32,
}

/// A stated column width.
#[derive(Debug, Clone, Copy, PartialEq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ColWidth {
    /// Zero-based column index.
    pub col: u32,
    /// Width in pixels, already converted from the file's character units.
    pub width: f64,
}

/// One sheet, as much of it as the caller asked for.
#[derive(Debug, Clone, PartialEq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SheetData {
    /// Name as the workbook spells it, which is what the tab bar shows.
    pub name: String,
    /// Total rows in the sheet, not in this window.
    pub row_count: u32,
    /// Total columns in the sheet, not in this window.
    pub col_count: u32,
    /// First row index included in rows.
    pub first_row: u32,
    /// First column index drawn. A sheet whose data starts at C3 has a first column of
    /// 2, and the view needs it to place a merge or a stated width on the right column.
    pub first_col: u32,
    /// Rows of this window, in order, sparse within each row.
    pub rows: Vec<SheetRow>,
    /// Merged blocks that intersect this window.
    pub merges: Vec<MergedRegion>,
    /// Column widths the file states. Empty means every column is the default width,
    /// which is what a sheet looks like before anyone resizes a column.
    pub col_widths: Vec<ColWidth>,
}

/// A whole workbook, with one sheet's window included.
#[derive(Debug, Clone, PartialEq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SpreadsheetModel {
    /// The id the annotations for this file are stored under.
    ///
    /// Derived from the path, size and mtime exactly as a deck's is, so the ink written
    /// against a spreadsheet survives a restart and is found again by the same file.
    pub deck_id: String,
    /// Every sheet name, in workbook order, for the tab bar.
    pub sheets: Vec<String>,
    /// The sheet whose rows are included.
    pub active: String,
    /// Zero-based index of the active sheet within sheets.
    pub active_index: u32,
    /// The window of the active sheet.
    pub sheet: SheetData,
    /// How the bytes were decoded, so the view can say so when it had to guess.
    pub encoding: SheetEncoding,
    /// True when the window is not the whole sheet, so the view keeps its scroller.
    pub truncated: bool,
}

/// How the bytes of a text-format sheet were decoded.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "lowercase")]
pub enum SheetEncoding {
    /// Read by calamine from a real spreadsheet container.
    Binary,
    /// UTF-8, with or without a byte order mark.
    Utf8,
    /// GBK / GB18030, which is what a Chinese-locale Excel writes by default.
    Gbk,
}

/// What a caller may ask for.
#[derive(Debug, Clone, Default)]
pub struct SheetRequest {
    /// Sheet to return. None or an empty name means the workbook's first sheet.
    pub sheet: Option<String>,
    /// First row to return, zero based and absolute within the sheet.
    pub first_row: u32,
    /// How many rows to return. Zero means DEFAULT_ROW_WINDOW.
    pub row_count: u32,
}

/// Open a workbook and return one window of one sheet.
///
/// The sheet is chosen by name so the renderer can switch tabs without reopening the
/// file, and a window is returned so a large sheet costs one screenful rather than all
/// of it.
pub fn open_spreadsheet(path: &Path, request: &SheetRequest) -> Result<SpreadsheetModel, String> {
    let ext = crate::detect::declared_ext(path);
    let mut model = if is_delimited_ext(&ext) {
        open_delimited(path, request, &ext)?
    } else {
        open_binary(path, request, &ext)?
    };
    model.deck_id = deck_id_for(path);
    Ok(model)
}

/// The annotation id for a source file.
///
/// The same derivation convert.rs uses for a deck, so one file has one id whether it was
/// opened natively or through the engine, and its annotations do not split in two.
fn deck_id_for(path: &Path) -> String {
    let meta = match std::fs::metadata(path) {
        Ok(meta) => meta,
        Err(_) => return String::new(),
    };
    let mtime_ms = meta
        .modified()
        .ok()
        .and_then(|time| time.duration_since(std::time::UNIX_EPOCH).ok())
        .map(|delta| delta.as_millis() as f64)
        .unwrap_or(0.0);
    // Bound to a local first: to_string_lossy returns a Cow, and taking a reference to
    // it inline would borrow a temporary that the struct outlives.
    let owned = path.to_string_lossy().to_string();
    crate::convert::deck_id_for(&crate::convert::SourceKey {
        path: &owned,
        bytes: meta.len(),
        mtime_ms,
    })
}

/// Whether an extension names a delimited text table rather than a workbook container.
pub fn is_delimited_ext(ext: &str) -> bool {
    // Only the two extensions that unambiguously mean "a delimited table". Plain .txt
    // is left out on purpose: it is the one extension a user is most likely to attach
    // to prose, and claiming it as a sheet would break opening a text file at all.
    matches!(ext, "csv" | "tsv")
}

// ---------------------------------------------------------------- binary workbooks

/// The sheet names and the requested sheet's range, from one concrete reader.
///
/// A macro rather than a generic function on purpose. Each reader type implements
/// Reader for its own stream type, so a generic helper would need a where-clause naming
/// the stream and the associated error to satisfy the compiler; expanding the four
/// calls instead lets each arm resolve against a concrete type, which is both simpler
/// and the shape the calamine examples use.
macro_rules! read_window {
    ($reader:expr, $request:expr) => {{
        let reader = $reader;
        let names = reader.sheet_names();
        let active = match $request.sheet.as_deref() {
            Some(wanted) if !wanted.is_empty() => wanted.to_string(),
            _ => names.first().cloned().unwrap_or_default(),
        };
        // A workbook with no sheets has nothing to ask for; the caller reports that.
        let range: Range<Data> = if active.is_empty() {
            Range::empty()
        } else {
            reader
                .worksheet_range(&active)
                .map_err(|err| format!("无法读取工作表 {active}：{err}"))?
        };
        (names, range)
    }};
}

/// Read one window out of a workbook calamine can open.
///
/// The concrete reader is dispatched explicitly rather than through the Sheets wrapper:
/// Sheets implements Reader for every RS at once, so a call through it leaves the reader
/// type unconstrained and does not compile. Matching the variants gives each arm a
/// concrete reader and therefore a concrete Reader impl.
fn open_binary(
    path: &Path,
    request: &SheetRequest,
    ext: &str,
) -> Result<SpreadsheetModel, String> {
    let mut workbook =
        open_workbook_auto(path).map_err(|err| format!("无法读取表格文件：{err}"))?;

    let (names, range) = match &mut workbook {
        Sheets::Xls(reader) => read_window!(reader, request),
        Sheets::Xlsx(reader) => read_window!(reader, request),
        Sheets::Xlsb(reader) => read_window!(reader, request),
        Sheets::Ods(reader) => read_window!(reader, request),
    };

    if names.is_empty() {
        return Err("表格文件里没有工作表".to_string());
    }

    let active_index = match request.sheet.as_deref() {
        Some(wanted) if !wanted.is_empty() => names
            .iter()
            .position(|name| name == wanted)
            .ok_or_else(|| format!("表格文件里没有名为 {wanted} 的工作表"))?,
        _ => 0,
    };
    let active = names[active_index].clone();

    // Merged regions and column widths are not part of calamine's unified range, so
    // they are read from the OOXML parts. A legacy .xls keeps them in a binary stream
    // this module does not walk, so it reports none and the grid draws unmerged; that
    // limitation is stated in the report rather than hidden.
    let geometry = if is_ooxml_ext(ext) {
        read_ooxml_geometry(path, &active)
    } else {
        Geometry::default()
    };

    let (sheet, truncated) = window_of(&active, &range, &geometry, request);
    Ok(SpreadsheetModel {
        // Filled in by open_spreadsheet, which is the only place that has the path.
        deck_id: String::new(),
        sheets: names,
        active,
        active_index: active_index as u32,
        sheet,
        encoding: SheetEncoding::Binary,
        truncated,
    })
}

/// Extensions whose container is OOXML, and whose parts zip_vfs can therefore read.
fn is_ooxml_ext(ext: &str) -> bool {
    matches!(ext, "xlsx" | "xlsm" | "xltx" | "xlsb")
}

/// Merged regions and column widths for one sheet.
#[derive(Debug, Clone, Default)]
struct Geometry {
    merges: Vec<MergedRegion>,
    widths: Vec<ColWidth>,
}

/// Read merged regions and column widths out of the OOXML parts.
///
/// A failure here is not an error: the sheet still draws, just without spans and at a
/// uniform column width, which is what it looks like before anyone formats it. That is
/// a far better outcome than refusing to open a workbook because one attribute was odd.
fn read_ooxml_geometry(path: &Path, sheet_name: &str) -> Geometry {
    let Ok(vfs) = crate::zip_vfs::ZipVfs::open(path) else {
        return Geometry::default();
    };
    let Some(part) = sheet_part_for(&vfs, sheet_name) else {
        return Geometry::default();
    };
    let Ok(xml) = vfs.read_text(&part) else {
        return Geometry::default();
    };

    Geometry {
        merges: parse_merged_regions(&xml),
        widths: parse_col_widths(&xml),
    }
}

/// Resolve a sheet name to its worksheet part, through the workbook relationships.
fn sheet_part_for(vfs: &crate::zip_vfs::ZipVfs, sheet_name: &str) -> Option<String> {
    let workbook = vfs.read_text("xl/workbook.xml").ok()?;
    let rels = vfs.read_text("xl/_rels/workbook.xml.rels").ok()?;

    let mut id = None;
    for tag in elements(&workbook, "sheet") {
        if attribute(&tag, "name").as_deref() == Some(sheet_name) {
            id = attribute(&tag, "r:id");
            break;
        }
    }
    let id = id?;

    let mut target = None;
    for tag in elements(&rels, "Relationship") {
        if attribute(&tag, "Id").as_deref() == Some(id.as_str()) {
            target = attribute(&tag, "Target");
            break;
        }
    }
    let target = target?;

    // A target may be absolute or relative to the workbook part, which lives in xl/.
    let normalised = target.trim_start_matches('/').to_string();
    if normalised.starts_with("xl/") {
        Some(normalised)
    } else {
        Some(format!("xl/{normalised}"))
    }
}

/// The opening tags of every element with the given name.
///
/// A hand-rolled scan rather than an XML parser: the fragments being read are
/// mergeCell and col elements, and pulling in a full parser to read two attributes of
/// a well-formed document would be a large dependency for a small job.
fn elements(xml: &str, name: &str) -> Vec<String> {
    let open = format!("<{name}");
    let mut out = Vec::new();
    let mut at = 0usize;
    while let Some(found) = xml[at..].find(&open) {
        let start = at + found;
        // A tag name ends at a delimiter, so <sheet must not match <sheets.
        let boundary = xml[start + open.len()..]
            .chars()
            .next()
            .map(|ch| ch.is_whitespace() || ch == '>' || ch == '/')
            .unwrap_or(false);
        if !boundary {
            at = start + open.len();
            continue;
        }
        let Some(end) = xml[start..].find('>') else {
            break;
        };
        out.push(xml[start..start + end + 1].to_string());
        at = start + end + 1;
    }
    out
}

/// Read one attribute out of an element's opening tag.
fn attribute(tag: &str, name: &str) -> Option<String> {
    let needle = format!("{name}=\"");
    let at = tag.find(&needle)?;
    let rest = &tag[at + needle.len()..];
    let end = rest.find('"')?;
    Some(rest[..end].to_string())
}

/// Parse the mergeCell elements of a worksheet into regions.
pub fn parse_merged_regions(xml: &str) -> Vec<MergedRegion> {
    let mut out = Vec::new();
    for tag in elements(xml, "mergeCell") {
        let Some(reference) = attribute(&tag, "ref") else {
            continue;
        };
        if let Some(region) = parse_region(&reference) {
            out.push(region);
        }
    }
    out
}

/// Parse an A1:C2 reference into a region.
///
/// A single-cell reference (A1) is a region of one cell, which is what a merge of one
/// cell means and is harmless to draw.
pub fn parse_region(reference: &str) -> Option<MergedRegion> {
    let (first, last) = match reference.split_once(':') {
        Some((a, b)) => (a, b),
        None => (reference, reference),
    };
    let (first_row, first_col) = parse_cell_ref(first)?;
    let (last_row, last_col) = parse_cell_ref(last)?;
    Some(MergedRegion {
        first_row: first_row.min(last_row),
        first_col: first_col.min(last_col),
        last_row: first_row.max(last_row),
        last_col: first_col.max(last_col),
    })
}

/// Parse B7 into zero-based (row, column).
pub fn parse_cell_ref(reference: &str) -> Option<(u32, u32)> {
    let mut col: u32 = 0;
    let mut row: u32 = 0;
    let mut seen_digit = false;
    let mut any_letter = false;
    for ch in reference.chars() {
        if ch.is_ascii_alphabetic() {
            if seen_digit {
                return None;
            }
            any_letter = true;
            // Base-26 with A=1, which is how a spreadsheet names a column.
            col = col
                .checked_mul(26)?
                .checked_add(ch.to_ascii_uppercase() as u32 - 'A' as u32 + 1)?;
        } else if ch.is_ascii_digit() {
            seen_digit = true;
            row = row.checked_mul(10)?.checked_add(ch as u32 - '0' as u32)?;
        } else if ch == '$' {
            continue;
        } else {
            return None;
        }
    }
    if !any_letter || !seen_digit || row == 0 {
        return None;
    }
    Some((row - 1, col.saturating_sub(1)))
}

/// Parse the col elements of a worksheet into column widths.
///
/// min and max are one-based and a single col element may cover a run of columns,
/// which is how Excel writes "these three columns are all 12.5 wide".
pub fn parse_col_widths(xml: &str) -> Vec<ColWidth> {
    let mut out = Vec::new();
    for tag in elements(xml, "col") {
        let Some(width) = attribute(&tag, "width").and_then(|w| w.parse::<f64>().ok()) else {
            continue;
        };
        // A width of zero is how a hidden column is written; drawing it at zero would
        // make the column unreachable, so it keeps the minimum instead.
        if width <= 0.0 {
            continue;
        }
        let min = attribute(&tag, "min")
            .and_then(|v| v.parse::<u32>().ok())
            .unwrap_or(1);
        let max = attribute(&tag, "max")
            .and_then(|v| v.parse::<u32>().ok())
            .unwrap_or(min);
        // A corrupt range must not expand into thousands of entries.
        if max < min || max - min > MAX_COLUMNS {
            continue;
        }
        for col in min..=max {
            out.push(ColWidth {
                col: col.saturating_sub(1),
                width: characters_to_pixels(width),
            });
        }
    }
    out
}

/// Convert an OOXML column width in characters to pixels.
///
/// Excel's width unit is the width of one digit in the workbook's default font. The
/// conversion below is the one the format documents: 7 pixels per character for the
/// default Calibri 11, plus the 5 pixels of cell padding a column always carries.
pub fn characters_to_pixels(characters: f64) -> f64 {
    (characters * 7.0 + 5.0).round()
}

/// Cut a window out of a worksheet range.
///
/// Row and column indices are absolute within the sheet, because that is the coordinate
/// space Range::get_value expects: the range starts at its first non-empty cell, which
/// for a sheet whose data begins at B2 is not (0, 0).
fn window_of(
    name: &str,
    range: &Range<Data>,
    geometry: &Geometry,
    request: &SheetRequest,
) -> (SheetData, bool) {
    let (height, width) = range.get_size();
    let row_count = height as u32;
    let col_count = (width as u32).min(MAX_COLUMNS);
    // Where the data actually starts. A range with no cells has no start, and then
    // there is nothing to draw and the window is empty either way.
    let origin_row = range.start().map(|(row, _)| row).unwrap_or(0);
    let origin_col = range.start().map(|(_, col)| col).unwrap_or(0);

    // Everything reported here is in ABSOLUTE sheet coordinates, not offsets into the
    // range. That is not cosmetic: a merge and a column width name a position in the
    // sheet, so a cell at B2 of a sheet whose data starts at B2 has to be column 1 for
    // the merge over A1:C1 and the width of column A to line up with it. Mixing the two
    // spaces put every merge one row and one column out on a sheet that does not start
    // at A1.
    let first_row = origin_row.saturating_add(request.first_row.min(row_count));
    let want = window_size(request);
    let last_row = first_row
        .saturating_add(want)
        .min(origin_row.saturating_add(row_count));

    let mut rows: Vec<SheetRow> = Vec::new();
    for abs_row in first_row..last_row {
        let mut cells: Vec<SheetCell> = Vec::new();
        for offset_col in 0..col_count {
            let abs_col = origin_col + offset_col;
            let Some(value) = range.get_value((abs_row, abs_col)) else {
                continue;
            };
            // An empty cell is not drawn and does not need to cross IPC: a sheet is
            // mostly empty, and sending every blank would multiply the payload.
            if matches!(value, Data::Empty) {
                continue;
            }
            cells.push(SheetCell {
                col: abs_col,
                text: display_text(value),
                kind: kind_of(value),
            });
        }
        if !cells.is_empty() {
            rows.push(SheetRow {
                row: abs_row,
                cells,
            });
        }
    }

    let merges = geometry
        .merges
        .iter()
        .copied()
        .filter(|region| region.last_row >= first_row && region.first_row < last_row)
        .collect();

    let sheet = SheetData {
        name: name.to_string(),
        row_count,
        col_count,
        first_row,
        first_col: origin_col,
        rows,
        merges,
        col_widths: geometry.widths.clone(),
    };
    (sheet, last_row < origin_row.saturating_add(row_count))
}

/// How many rows this request wants.
fn window_size(request: &SheetRequest) -> u32 {
    match request.row_count {
        0 => DEFAULT_ROW_WINDOW,
        asked => asked.min(MAX_ROW_WINDOW),
    }
}

/// Which kind of value a cell holds.
fn kind_of(value: &Data) -> CellKind {
    match value {
        Data::String(_) => CellKind::Text,
        Data::Float(_) | Data::Int(_) => CellKind::Number,
        Data::Bool(_) => CellKind::Bool,
        Data::DateTime(_) | Data::DateTimeIso(_) | Data::DurationIso(_) => CellKind::Date,
        Data::Error(_) => CellKind::Text,
        // A blank is filtered out before it reaches here.
        Data::Empty => CellKind::Text,
    }
}

/// The text a user expects to see for a cell.
///
/// A number is printed without a trailing .0, because that is how Excel shows a whole
/// number. A DateTime is printed as its serial value: calamine's Display for it does
/// the same, and this module has no calendar to turn a serial into a date, so the view
/// is told the kind and decides how to draw it.
pub fn display_text(value: &Data) -> String {
    match value {
        Data::Empty => String::new(),
        Data::String(text) => text.clone(),
        Data::Float(number) => format_number(*number),
        Data::Int(number) => number.to_string(),
        Data::Bool(flag) => {
            if *flag {
                "TRUE".to_string()
            } else {
                "FALSE".to_string()
            }
        }
        Data::DateTime(excel) => format_number(excel.as_f64()),
        Data::DateTimeIso(text) => text.clone(),
        Data::DurationIso(text) => text.clone(),
        Data::Error(error) => format!("{error}"),
    }
}

/// Format a float the way a spreadsheet shows it.
///
/// Fifteen significant digits is the precision a double can carry and the limit Excel
/// itself applies, so 0.1 + 0.2 reads as 0.3 rather than as 0.30000000000000004.
pub fn format_number(number: f64) -> String {
    if !number.is_finite() {
        return if number.is_nan() {
            "#NUM!".to_string()
        } else if number > 0.0 {
            "#DIV/0!".to_string()
        } else {
            "-#DIV/0!".to_string()
        };
    }
    if number == number.trunc() && number.abs() < 1e15 {
        return format!("{}", number as i64);
    }
    let rounded = format!("{number:.15}");
    let trimmed = rounded.trim_end_matches('0').trim_end_matches('.');
    if trimmed.is_empty() || trimmed == "-" {
        "0".to_string()
    } else {
        trimmed.to_string()
    }
}

// ---------------------------------------------------------------- delimited text

fn open_delimited(
    path: &Path,
    request: &SheetRequest,
    ext: &str,
) -> Result<SpreadsheetModel, String> {
    let bytes = std::fs::read(path).map_err(|err| format!("无法读取表格文件：{err}"))?;
    if bytes.len() as u64 > MAX_TEXT_BYTES {
        return Err("文件超过 200 MB，无法打开".to_string());
    }
    let (text, encoding) = decode_text(&bytes);

    let delimiter = delimiter_for(&text, ext);
    let table = parse_delimited(&text, delimiter);

    let name = sheet_name_for(path);
    let row_count = table.len() as u32;
    let col_count = table
        .iter()
        .map(|row| row.len())
        .max()
        .unwrap_or(0)
        .min(MAX_COLUMNS as usize) as u32;

    let first_row = request.first_row.min(row_count);
    let want = window_size(request);
    let last_row = first_row.saturating_add(want).min(row_count);

    let mut rows: Vec<SheetRow> = Vec::new();
    for (index, row) in table
        .iter()
        .enumerate()
        .take(last_row as usize)
        .skip(first_row as usize)
    {
        let mut cells: Vec<SheetCell> = Vec::new();
        for (col, text) in row.iter().enumerate().take(col_count as usize) {
            if text.is_empty() {
                continue;
            }
            // A CSV has no types at all: every field is text. Guessing numbers would
            // turn a course code such as 0101 into 101, which is a real and common
            // corruption of Chinese teaching material.
            cells.push(SheetCell {
                col: col as u32,
                text: text.clone(),
                kind: CellKind::Text,
            });
        }
        if !cells.is_empty() {
            rows.push(SheetRow {
                row: index as u32,
                cells,
            });
        }
    }

    let sheet = SheetData {
        name: name.clone(),
        row_count,
        col_count,
        first_row,
        // A delimited table always starts at A1.
        first_col: 0,
        rows,
        merges: Vec::new(),
        col_widths: Vec::new(),
    };

    Ok(SpreadsheetModel {
        deck_id: String::new(),
        sheets: vec![name.clone()],
        active: name,
        active_index: 0,
        truncated: last_row < row_count,
        sheet,
        encoding,
    })
}

/// Decode a text file, preferring UTF-8 and falling back to GBK.
///
/// The fallback is the point: a CSV exported from Excel on a Chinese Windows is in GBK,
/// and reading it as UTF-8 turns every Chinese character into a replacement character.
/// The order matters as well: every ASCII byte is valid UTF-8, so UTF-8 must be tried
/// first or a plain ASCII file would be reported as an encoding guess.
pub fn decode_text(bytes: &[u8]) -> (String, SheetEncoding) {
    // A byte order mark is definitive, and stripping it keeps it out of the first cell.
    if let Some(rest) = bytes.strip_prefix(&[0xEF, 0xBB, 0xBF]) {
        return (
            String::from_utf8_lossy(rest).into_owned(),
            SheetEncoding::Utf8,
        );
    }
    match std::str::from_utf8(bytes) {
        Ok(text) => (text.to_string(), SheetEncoding::Utf8),
        // Not valid UTF-8, so it is almost certainly a legacy code page.
        Err(_) => (decode_gbk(bytes), SheetEncoding::Gbk),
    }
}

/// Decode a two-byte GBK stream through the generated table.
///
/// Anything outside the table becomes U+FFFD rather than being dropped, so a bad byte
/// never changes a row's column count.
pub fn decode_gbk(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len());
    let mut at = 0usize;
    while at < bytes.len() {
        let first = bytes[at];
        if first < 0x80 {
            out.push(first as char);
            at += 1;
            continue;
        }
        if (0x81..=0xFE).contains(&first) && at + 1 < bytes.len() {
            let second = bytes[at + 1];
            if (0x40..=0xFE).contains(&second) && second != 0x7F {
                if let Some(ch) = gbk_char(first, second) {
                    out.push(ch);
                    at += 2;
                    continue;
                }
            }
        }
        out.push('\u{FFFD}');
        at += 1;
    }
    out
}

/// Look one two-byte pair up in the table.
fn gbk_char(lead: u8, trail: u8) -> Option<char> {
    let lead_index = (lead as usize).checked_sub(0x81)?;
    // 0x7F is not a trail byte, so the index skips it.
    let trail_index = if trail < 0x7F {
        (trail as usize).checked_sub(0x40)?
    } else {
        (trail as usize).checked_sub(0x41)?
    };
    if lead_index >= GBK_LEADS || trail_index >= GBK_TRAILS {
        return None;
    }
    let at = (lead_index * GBK_TRAILS + trail_index) * 2;
    let low = *GBK_TABLE.get(at)? as u32;
    let high = *GBK_TABLE.get(at + 1)? as u32;
    let code = low | (high << 8);
    if code == 0 {
        return None;
    }
    char::from_u32(code)
}

/// Which separator a delimited file uses.
///
/// The extension is a hint, but a tab-separated file named .csv exists in the wild, and
/// a semicolon-separated file is what a European locale produces. Counting separators
/// in the first line is a one-pass answer that does not depend on the name.
pub fn delimiter_for(text: &str, ext: &str) -> u8 {
    if ext == "tsv" {
        return b'\t';
    }
    let first = text.lines().next().unwrap_or("");
    let commas = first.matches(',').count();
    let tabs = first.matches('\t').count();
    let semicolons = first.matches(';').count();
    if tabs > commas && tabs >= semicolons {
        return b'\t';
    }
    // Treating a semicolon file as comma-separated puts the whole row in one cell.
    if semicolons > commas {
        return b';';
    }
    b','
}

/// Split delimited text into a table of fields.
///
/// Quoting follows RFC 4180: a field may be wrapped in double quotes, may contain the
/// delimiter and newlines, and a doubled quote inside it is one literal quote. A file
/// with an unbalanced quote is read to the end rather than dropped, because half a
/// table is more useful than none.
pub fn parse_delimited(text: &str, delimiter: u8) -> Vec<Vec<String>> {
    let bytes = text.as_bytes();
    let mut rows: Vec<Vec<String>> = Vec::new();
    let mut row: Vec<String> = Vec::new();
    let mut field = String::new();
    let mut quoted = false;
    let mut at = 0usize;

    while at < bytes.len() {
        let byte = bytes[at];
        if quoted {
            if byte == b'"' {
                if at + 1 < bytes.len() && bytes[at + 1] == b'"' {
                    field.push('"');
                    at += 2;
                    continue;
                }
                quoted = false;
                at += 1;
                continue;
            }
            // Push the whole UTF-8 sequence so a multi-byte character is never split.
            let end = (at + utf8_width(byte)).min(bytes.len());
            field.push_str(&String::from_utf8_lossy(&bytes[at..end]));
            at = end;
            continue;
        }

        match byte {
            b'"' if field.is_empty() => {
                quoted = true;
                at += 1;
            }
            b'\r' => {
                // CRLF and a lone CR both end the row.
                if at + 1 < bytes.len() && bytes[at + 1] == b'\n' {
                    at += 1;
                }
                row.push(std::mem::take(&mut field));
                rows.push(std::mem::take(&mut row));
                at += 1;
            }
            b'\n' => {
                row.push(std::mem::take(&mut field));
                rows.push(std::mem::take(&mut row));
                at += 1;
            }
            _ if byte == delimiter => {
                row.push(std::mem::take(&mut field));
                at += 1;
            }
            _ => {
                let end = (at + utf8_width(byte)).min(bytes.len());
                field.push_str(&String::from_utf8_lossy(&bytes[at..end]));
                at = end;
            }
        }
    }

    // A file that does not end with a newline still has a last row, and an empty
    // trailing field after a final delimiter is a real field.
    if !field.is_empty() || !row.is_empty() {
        row.push(field);
        rows.push(row);
    }
    rows
}

/// How many bytes the UTF-8 sequence starting with this byte occupies.
fn utf8_width(first: u8) -> usize {
    if first < 0x80 {
        1
    } else if first >> 5 == 0b110 {
        2
    } else if first >> 4 == 0b1110 {
        3
    } else if first >> 3 == 0b11110 {
        4
    } else {
        1
    }
}

/// The tab-bar name for a delimited file.
///
/// A CSV holds one table, so its name is the file's own name; the stem keeps the tab
/// short while still telling two files apart.
fn sheet_name_for(path: &Path) -> String {
    path.file_stem()
        .map(|stem| stem.to_string_lossy().to_string())
        .unwrap_or_else(|| "Sheet1".to_string())
}

